"""Query logging for RAG operations."""

import json
import logging
from datetime import datetime
from typing import Any, Dict, List, Optional
from sqlalchemy import text
from sqlalchemy.orm import Session
from sqlalchemy.exc import SQLAlchemyError

logger = logging.getLogger(__name__)


def log_query(
    session: Session,
    question: str,
    answer: Optional[str],
    retrieved: Optional[List[Dict[str, Any]]] = None,
    top_k: int = 5,
    embedding_model: Optional[str] = None,
    llm_model: Optional[str] = None,
    tokens_in: Optional[int] = None,
    tokens_out: Optional[int] = None,
    latency_retrieval_ms: Optional[int] = None,
    latency_llm_ms: Optional[int] = None,
    latency_total_ms: Optional[int] = None,
    status: str = "ok",
    error: Optional[str] = None,
) -> bool:
    """
    Log a RAG query to the database.
    
    Args:
        session: SQLAlchemy session
        question: User question
        answer: Generated answer
        retrieved: List of retrieved chunks with scores
        top_k: Search parameter
        embedding_model: Model used for retrieval
        llm_model: Model used for generation
        tokens_in: Tokens consumed by LLM input
        tokens_out: Tokens generated by LLM
        latency_retrieval_ms: Time for retrieval stage
        latency_llm_ms: Time for LLM generation
        latency_total_ms: Total query time
        status: 'ok' or 'error'
        error: Error message if status is 'error'
    
    Returns:
        True if logging succeeded, False otherwise
    """
    
    try:
        sql = text("""
            INSERT INTO query_logs (
                question, answer, retrieved, top_k,
                embedding_model, llm_model,
                tokens_in, tokens_out,
                latency_retrieval_ms, latency_llm_ms, latency_total_ms,
                status, error, created_at
            ) VALUES (
                :question, :answer, :retrieved, :top_k,
                :embedding_model, :llm_model,
                :tokens_in, :tokens_out,
                :latency_retrieval_ms, :latency_llm_ms, :latency_total_ms,
                :status, :error, :created_at
            )
        """)
        
        session.execute(sql, {
            "question": question,
            "answer": answer,
            "retrieved": json.dumps(retrieved) if retrieved else None,
            "top_k": top_k,
            "embedding_model": embedding_model,
            "llm_model": llm_model,
            "tokens_in": tokens_in,
            "tokens_out": tokens_out,
            "latency_retrieval_ms": latency_retrieval_ms,
            "latency_llm_ms": latency_llm_ms,
            "latency_total_ms": latency_total_ms,
            "status": status,
            "error": error,
            "created_at": datetime.utcnow(),
        })
        session.commit()
        
        return True
        
    except SQLAlchemyError as e:
        logger.error(f"Failed to log query: {e}")
        # Don't raise - let the query complete even if logging fails
        return False
